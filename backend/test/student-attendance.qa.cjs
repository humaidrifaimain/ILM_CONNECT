async function request(endpoint, user, method = 'GET', body, status = 200) {
  const response = await fetch(api + endpoint, { method, headers: { 'Content-Type': 'application/json', ...(user ? { Authorization: 'Bearer ' + user.token } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json();
  assert.equal(response.status, status, endpoint + ': ' + JSON.stringify(data));
  assert.match(response.headers.get('content-type'), /application\/json/);
  return data;
}
