async function webhook(row, user, event = 'participant_joined', createdAt = Math.floor(Date.now() / 1000), signed = true, contentType = 'application/webhook+json') {
  const body = JSON.stringify({ event, room: { name: row.livekitRoomName }, participant: { identity: 'student:' + user.id }, createdAt: String(createdAt), id: crypto.randomUUID() });
  const token = new AccessToken('attendance-qa-key', webhookSecret);
  token.sha256 = crypto.createHash('sha256').update(body).digest('base64');
  const response = await fetch(api + '/livekit/webhook', { method: 'POST', headers: { 'Content-Type': contentType, ...(signed ? { Authorization: await token.toJwt() } : {}) }, body });
  return { response, data: await response.json(), body, token };
}
